import assert from "node:assert/strict";
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { afterEach, test } from "node:test";
import type { FrameworkProject, FrameworkSurface } from "@/core/paywalls/project/framework";
import {
  TYPES_FILE,
  collectProjectDeclarations,
  projectTypes,
  writeProjectTypes,
} from "@/core/paywalls/project/types";
import type { Framework } from "@/core/paywalls/project/framework";

const dirs: string[] = [];

afterEach(() => {
  while (dirs.length > 0) {
    const dir = dirs.pop();
    if (dir) fs.rmSync(dir, { recursive: true, force: true });
  }
});

function tempDir(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "superwall-routes-"));
  dirs.push(dir);
  return dir;
}

function surface(id: string, names: string[]): FrameworkSurface {
  return {
    kind: "paywall",
    id,
    dir: `/tmp/${id}`,
    configFile: `/tmp/${id}/config.ts`,
    routes: names.map((name) => ({ name, file: `/tmp/${id}/app/${name}.tsx` })),
  };
}

function project(superwallDir: string, surfaces: FrameworkSurface[]): FrameworkProject {
  return { root: superwallDir, superwallDir, surfaces, diagnostics: [] };
}

test("the generated file carries the asset reference and the route union", () => {
  const types = projectTypes(project("/tmp", [surface("a", ["index", "plans"])]));

  assert.match(types, /<reference types="superwall\/assets" \/>/);
  assert.match(types, /declare module "superwall\/navigation"/);
  assert.match(types, /interface SuperwallRoutes \{/);
  assert.match(types, /"index": true;/);
  assert.match(types, /"plans": true;/);
});

test("names are sorted and deduplicated across every surface", () => {
  const types = projectTypes(
    project("/tmp", [
      surface("a", ["plans", "index"]),
      surface("b", ["index", "goals/experience"]),
    ]),
  );

  const names = [...types.matchAll(/"(.+)": true;/g)].map((match) => match[1]);
  assert.deepEqual(names, ["goals/experience", "index", "plans"]);
});

test("nested route names survive JSON quoting", () => {
  const types = projectTypes(project("/tmp", [surface("a", ["index", "goals/experience"])]));

  assert.match(types, /"goals\/experience": true;/);
});

test("the file lands in the superwall directory", () => {
  const dir = tempDir();
  writeProjectTypes(project(dir, [surface("a", ["index"])]));

  const file = path.join(dir, TYPES_FILE);
  assert.equal(fs.existsSync(file), true);
  assert.match(fs.readFileSync(file, "utf8"), /"index": true;/);
});

test("rewrites when routes change", () => {
  const dir = tempDir();
  writeProjectTypes(project(dir, [surface("a", ["index"])]));
  writeProjectTypes(project(dir, [surface("a", ["index", "plans"])]));

  assert.match(fs.readFileSync(path.join(dir, TYPES_FILE), "utf8"), /"plans": true;/);
});

test("leaves the file untouched when nothing changed — no needless dev-server churn", () => {
  const dir = tempDir();
  const built = project(dir, [surface("a", ["index"])]);
  writeProjectTypes(built);
  const file = path.join(dir, TYPES_FILE);
  const before = fs.statSync(file).mtimeMs;

  writeProjectTypes(built);

  assert.equal(fs.statSync(file).mtimeMs, before);
});

test("a project with no surfaces still gets asset types, just no route union", () => {
  const dir = tempDir();
  writeProjectTypes(project(dir, []));

  const written = fs.readFileSync(path.join(dir, TYPES_FILE), "utf8");
  assert.match(written, /<reference types="superwall\/assets" \/>/);
  assert.doesNotMatch(written, /SuperwallRoutes/);
});

test("it says plainly that the file is generated, committed, and not to be deleted", () => {
  const types = projectTypes(project("/tmp", [surface("a", ["index"])]));

  assert.match(types, /Generated by the Superwall CLI/);
  assert.match(types, /Commit it; don't edit it, and don't delete it/);
});

test("the two files it replaces are cleaned up, but only if we wrote them", () => {
  const dir = tempDir();
  fs.writeFileSync(path.join(dir, "superwall-env.d.ts"), "// Managed by the Superwall CLI.\n");
  fs.writeFileSync(path.join(dir, "superwall-routes.d.ts"), "// Generated by the Superwall CLI.\n");
  fs.writeFileSync(path.join(dir, "superwall-notes.d.ts"), "// mine, keep it\n");

  writeProjectTypes(project(dir, [surface("a", ["index"])]));

  assert.equal(fs.existsSync(path.join(dir, "superwall-env.d.ts")), false);
  assert.equal(fs.existsSync(path.join(dir, "superwall-routes.d.ts")), false);
  assert.equal(fs.existsSync(path.join(dir, "superwall-notes.d.ts")), true);
});

test("a hand-written file under the old name is left alone", () => {
  const dir = tempDir();
  const mine = "// my own declarations\ndeclare const x: number;\n";
  fs.writeFileSync(path.join(dir, "superwall-env.d.ts"), mine);

  writeProjectTypes(project(dir, [surface("a", ["index"])]));

  assert.equal(fs.readFileSync(path.join(dir, "superwall-env.d.ts"), "utf8"), mine);
});

test("an unwritable directory is survivable — types are a convenience, not a gate", () => {
  assert.doesNotThrow(() =>
    writeProjectTypes(project("/nope/does/not/exist", [surface("a", ["index"])])),
  );
});

test("collectProjectDeclarations keeps products and per-surface platforms from the framework payload", async () => {
  const framework: Framework = {
    discoverProject: () => {
      throw new Error("unused");
    },
    buildSnapshot: async () => {
      throw new Error("unused");
    },
    startPreviewServer: async () => ({}),
    studioProject: async () => {
      const surfaces: {
        kind?: string;
        id?: string;
        products: Record<string, string>;
        productIds?: Record<string, string[]>;
        platforms?: string[];
      }[] = [
        {
          kind: "paywall",
          id: "a",
          products: { monthly: "m", annual: "y_ios" },
          productIds: { monthly: ["m"], annual: ["y_ios", "y_play"] },
          platforms: ["ios", "android"],
        },
        { kind: "funnel", id: "b", products: { annual: "y" } },
        { products: { stray: "s" } },
      ];
      return { surfaces };
    },
  };

  const declarations = await collectProjectDeclarations(framework, "/tmp");
  assert.deepEqual(declarations.products, {
    monthly: ["m"],
    annual: ["y_ios", "y_play", "y"],
    stray: ["s"],
  });
  assert.deepEqual(declarations.platforms, { "paywall/a": ["ios", "android"], "funnel/b": undefined });
});

test("a framework without studioProject, or one that throws, declares nothing", async () => {
  const bare: Framework = {
    discoverProject: () => {
      throw new Error("unused");
    },
    buildSnapshot: async () => {
      throw new Error("unused");
    },
    startPreviewServer: async () => ({}),
  };
  assert.deepEqual(await collectProjectDeclarations(bare, "/tmp"), { products: {}, platforms: {} });
  assert.deepEqual(
    await collectProjectDeclarations(
      {
        ...bare,
        studioProject: async () => {
          throw new Error("broken config");
        },
      },
      "/tmp",
    ),
    { products: {}, platforms: {} },
  );
});

test("a reference is Stripe-typed when any platform's id is a Stripe price", () => {
  const types = projectTypes(project("/tmp", [surface("a", ["index"])]), {
    annual: ["pro_year", "pro_year_play"],
    plus: ["pro_plus", "live:price_1:trial"],
  });

  assert.match(types, /interface SuperwallProducts \{\n    "annual": true;\n    "plus": true;\n  \}/);
  assert.match(types, /interface SuperwallStripeProducts \{\n    "plus": true;\n  \}/);
});
