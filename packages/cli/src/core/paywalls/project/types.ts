import * as fs from "node:fs";
import * as path from "node:path";
import type { Framework, FrameworkProject } from "./framework";

export const TYPES_FILE = "superwall.d.ts";

const SUPERSEDED = ["superwall-env.d.ts", "superwall-routes.d.ts"];

const HEADER = `// Generated by the Superwall CLI. Commit it; don't edit it, and don't delete it.
// It is what makes \`import hero from "./assets/hero.jpg"\` typecheck and what
// makes router.push("...") autocomplete and reject typos. \`superwall dev\`
// rewrites it whenever your app/ directories change.

/// <reference types="superwall/assets" />
`;

const routeBlock = (names: readonly string[]): string =>
  [
    'declare module "superwall/navigation" {',
    "  interface SuperwallRoutes {",
    ...names.map((name) => `    ${JSON.stringify(name)}: true;`),
    "  }",
    "}",
    "",
    'export type SuperwallRouteName = keyof import("superwall/navigation").SuperwallRoutes;',
  ].join("\n");


const isStripeIdentifier = (identifier: string): boolean =>
  /^(test|live):price_[^:]+/.test(identifier);

const productBlock = (references: readonly string[], stripe: readonly string[]): string =>
  [
    'declare module "superwall/hooks" {',
    "  interface SuperwallProducts {",
    ...references.map((name) => `    ${JSON.stringify(name)}: true;`),
    "  }",
    "",
    "  interface SuperwallStripeProducts {",
    ...stripe.map((name) => `    ${JSON.stringify(name)}: true;`),
    "  }",
    "}",
  ].join("\n");

export interface ProjectDeclarations {
  products: Record<string, string[]>;
  platforms: Record<string, string[] | undefined>;
}

const productIdsOf = (surface: {
  products: Record<string, string>;
  productIds?: Record<string, string[]>;
}): Record<string, string[]> =>
  surface.productIds ??
  Object.fromEntries(Object.entries(surface.products).map(([reference, id]) => [reference, [id]]));

const declaredPlatforms = (value: unknown): string[] | undefined =>
  Array.isArray(value) && value.every((entry) => typeof entry === "string")
    ? value
    : undefined;

export async function collectProjectDeclarations(
  framework: Framework,
  root: string,
): Promise<ProjectDeclarations> {
  const declarations: ProjectDeclarations = { products: {}, platforms: {} };
  if (!framework.studioProject) return declarations;
  try {
    const payload = await framework.studioProject(root);
    for (const surface of payload.surfaces) {
      for (const [reference, ids] of Object.entries(productIdsOf(surface))) {
        declarations.products[reference] = [
          ...new Set([...(declarations.products[reference] ?? []), ...ids]),
        ];
      }
      if (typeof surface.kind === "string" && typeof surface.id === "string") {
        declarations.platforms[`${surface.kind}/${surface.id}`] = declaredPlatforms(
          surface.platforms,
        );
      }
    }
    return declarations;
  } catch {
    return declarations;
  }
}

export function projectTypes(
  project: FrameworkProject,
  products: Record<string, readonly string[]> = {},
): string {
  const names = new Set<string>();
  for (const surface of project.surfaces) {
    for (const route of surface.routes) names.add(route.name);
  }

  const sorted = [...names].sort();
  const sortedProducts = Object.keys(products).sort();
  const sortedStripe = sortedProducts.filter((name) =>
    (products[name] ?? []).some((identifier) => isStripeIdentifier(identifier)),
  );

  const blocks = [
    sorted.length > 0 ? routeBlock(sorted) : "",
    sortedProducts.length > 0 ? productBlock(sortedProducts, sortedStripe) : "",
  ].filter(Boolean);

  return blocks.length === 0 ? `${HEADER}\nexport {};\n` : `${HEADER}\n${blocks.join("\n\n")}\n`;
}

export function writeProjectTypes(
  project: FrameworkProject,
  products: Record<string, readonly string[]> = {},
): void {
  const file = path.join(project.superwallDir, TYPES_FILE);
  const next = projectTypes(project, products);
  try {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== next) {
      fs.writeFileSync(file, next);
    }
  } catch {
    return;
  }

  for (const name of SUPERSEDED) {
    const stale = path.join(project.superwallDir, name);
    try {
      if (fs.readFileSync(stale, "utf8").includes("Superwall CLI")) fs.rmSync(stale);
    } catch {
      continue;
    }
  }
}
