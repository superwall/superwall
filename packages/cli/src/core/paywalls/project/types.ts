import * as fs from "node:fs";
import * as path from "node:path";
import type { FrameworkProject } from "./framework";

export const TYPES_FILE = "superwall.d.ts";

const SUPERSEDED = ["superwall-env.d.ts", "superwall-routes.d.ts"];

const HEADER = `// Generated by the Superwall CLI. Commit it; don't edit it, and don't delete it.
// It is what makes \`import hero from "./assets/hero.jpg"\` typecheck and what
// makes router.push("...") autocomplete and reject typos. \`superwall dev\`
// rewrites it whenever your app/ directories change.

/// <reference types="superwall/assets" />
`;

const routeBlock = (names: readonly string[]): string =>
  [
    'declare module "superwall/navigation" {',
    "  interface SuperwallRoutes {",
    ...names.map((name) => `    ${JSON.stringify(name)}: true;`),
    "  }",
    "}",
    "",
    'export type SuperwallRouteName = keyof import("superwall/navigation").SuperwallRoutes;',
  ].join("\n");

export function projectTypes(project: FrameworkProject): string {
  const names = new Set<string>();
  for (const surface of project.surfaces) {
    for (const route of surface.routes) names.add(route.name);
  }
  const sorted = [...names].sort();

  return sorted.length === 0 ? `${HEADER}\nexport {};\n` : `${HEADER}\n${routeBlock(sorted)}\n`;
}

export function writeProjectTypes(project: FrameworkProject): void {
  const file = path.join(project.superwallDir, TYPES_FILE);
  const next = projectTypes(project);
  try {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== next) {
      fs.writeFileSync(file, next);
    }
  } catch {
    return;
  }

  for (const name of SUPERSEDED) {
    const stale = path.join(project.superwallDir, name);
    try {
      if (fs.readFileSync(stale, "utf8").includes("Superwall CLI")) fs.rmSync(stale);
    } catch {
      continue;
    }
  }
}
